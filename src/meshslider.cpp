float clipFloat(float v, float lo, float hi) {
  if (v < lo)
    return lo;
  if (v > hi)
    return hi;
  return v;
}

float smoothstep(float t) {
  t = clipFloat(t, 0.0f, 1.0f);
  return t * t * (3.0f - 2.0f * t);
}

float dotProduct(Vector2 a, Vector2 b) { return a.x * b.x + a.y * b.y; }
Vector2 addVectors(Vector2 a, Vector2 b) { return {a.x + b.x, a.y + b.y}; }
Vector2 subVectors(Vector2 a, Vector2 b) { return {a.x - b.x, a.y - b.y}; }
Vector2 scaleVector(Vector2 v, float s) { return {v.x * s, v.y * s}; }

Color gradientAt(float position, const Color &accent) {
  if (position >= AA_PORTION) {
    float gradient = clipFloat(
        (position - BORDER_PORTION) / (1.0f - BORDER_PORTION), 0.0f, 1.0f);
    float bodyAlpha =
        OPACITY_AT_EDGE - (OPACITY_AT_EDGE - OPACITY_AT_CENTRE) * gradient;
    float bright = 0.5f;
    if (!Global.flatSliders)
      bright = 0.5f + 0.5f * smoothstep(gradient); // rim -> centre: accent/2 -> accent
    Color bodyColour = Fade(
        Color{static_cast<unsigned char>(accent.r * bright),
              static_cast<unsigned char>(accent.g * bright),
              static_cast<unsigned char>(accent.b * bright), 255},
        clipFloat(bodyAlpha, 0.0f, 1.0f));
    const float innerStart = BORDER_PORTION - AA_PORTION * 0.5f;
    const float innerEnd = BORDER_PORTION + AA_PORTION * 0.5f;

    if (position <= innerStart) {
      return WHITE;
    }
    if (position < innerEnd) {
      float t = smoothstep((position - innerStart) / (innerEnd - innerStart));
      return Color{
          static_cast<unsigned char>(255.0f + (bodyColour.r - 255.0f) * t),
          static_cast<unsigned char>(255.0f + (bodyColour.g - 255.0f) * t),
          static_cast<unsigned char>(255.0f + (bodyColour.b - 255.0f) * t),
          static_cast<unsigned char>(255.0f + (bodyColour.a - 255.0f) * t)};
    }
    return bodyColour; // well i can make gradients too so ye
  }

  // Outer band: the white border's AA hands off straight into the shadow, so
  // there is no transparent gap between the two. Shadow peaks at the visual
  // edge (position 0) and smoothstep-fades out at the rim.
  float shadowDepth = MESH_SLIDER_SHADOW_SCALE - 1.0f;
  float whiteA = clipFloat(position / AA_PORTION, 0.0f, 1.0f);
  float shadowA;
  if (position >= 0.0f)
    shadowA = SHADOW_ALPHA * (1.0f - whiteA);
  else
    shadowA = SHADOW_ALPHA * (1.0f - smoothstep(-position / shadowDepth));

  float outA = whiteA + shadowA * (1.0f - whiteA);
  Color out = {0, 0, 0, static_cast<unsigned char>(outA * 255.0f)};
  if (outA > 0.0f) {
    out.r = static_cast<unsigned char>(255.0f * whiteA / outA);
    out.g = out.r;
    out.b = out.r;
  }
  return out;
}

// u (0 = centre line, 1 = rim)
float lutCoord(float u) {
  return (0.5f + u * (float)(LUT_SIZE - 1)) /
        (float)(LUT_SIZE);
}


// this function creates a texture that i can then sample for the sliders
void renderLut(RenderTexture2D &target, const Color &accent) {
  BeginTextureMode(&target);
  ClearBackground({0, 0, 0, 0});
  rlSetBlendFactorsSeparate(RL_ONE, RL_ZERO, RL_ONE, RL_ZERO, REPLACE_EQUATION,
                            REPLACE_EQUATION);
  rlSetBlendMode(RL_BLEND_CUSTOM_SEPARATE);
  for (int x = 0; x < LUT_SIZE; x++) {
    float u = (float)x / (LUT_SIZE - 1);
    Color colour = gradientAt(1.0f - u * MESH_SLIDER_SHADOW_SCALE, accent);
    DrawRectangleV({x, 0.0f},
                   {1.0f, LUT_ROWS}, colour);
  }
  EndBlendMode();
  EndTextureMode();
  SetTextureFilter(&target.texture, TEXTURE_FILTER_BILINEAR);
}


// So that we dont constantly redraw the lut, we sacrifice some memory
// but cache em. 
RenderTexture2D *getLut(const Color &accent) {
  uint32_t key = (uint32_t(accent.r) << 17) | (uint32_t(accent.g) << 9) |
                 (uint32_t(accent.b) << 1) | (Global.flatSliders ? 1 : 0);
  for (size_t i = 0; i < lutCount; i++)
    if (luts[i].key == key)
      return &luts[i].target;

  LutEntry *slot = nullptr;
  if (lutCount < MAX_LUTS) {
    RenderTexture2D rt = LoadRenderTexture(LUT_SIZE, LUT_ROWS);
    if (rt.id == 0)
      return nullptr;
    slot = &luts[lutCount++];
    slot->target = rt;
  } else {
    slot = &luts[lutEvictCursor++ % MAX_LUTS];
  }
  slot->key = key;
  renderLut(slot->target, accent);
  return &slot->target;
}

// yeah uh, online
void dedupePoints(std::vector<Vector2> &p, float eps) {
  if (p.empty())
    return;
  size_t w = 1;
  for (size_t i = 1; i < p.size(); i++) {
    Vector2 d = subVectors(p[i], p[w - 1]);
    if (sqrtf(dotProduct(d, d)) > eps)
      p[w++] = p[i];
  }
  p.resize(w);
}

// Ramer-Douglas-Peucker with an explicit error bound
// check wikipedia, actually cool algorithm
std::vector<Vector2> simplifyPath(const std::vector<Vector2> &pts, float eps) {
  int n = (int)(pts.size());
  if (n <= 2)
    return pts;
  int numkeep = 2;
  std::vector<char> keep(static_cast<size_t>(n), 0);
  keep[0] = keep[n - 1] = 1;
  std::vector<std::pair<int, int>> stack;
  stack.reserve(n + 1);
  stack.push_back(std::make_pair(0, n - 1));
  const float eps2 = eps * eps;
  while (!stack.empty()) {
    std::pair<int, int> range = stack.back();
    stack.pop_back();
    int a = range.first, b = range.second;
    if (b <= a + 1)
      continue;
    Vector2 A = pts[a];
    Vector2 d = subVectors(pts[b], A);
    float len2 = dotProduct(d, d);
    float worst = -1.0f;
    int worstIdx = -1;
    for (int i = a + 1; i < b; i++) {
      Vector2 ap = subVectors(pts[i], A);
      float dist2;
      if (len2 < 1e-12f) {
        dist2 = dotProduct(ap, ap);
      } else {
        float t = clipFloat(dotProduct(ap, d) / len2, 0.0f, 1.0f);
        Vector2 q = subVectors(ap, scaleVector(d, t));
        dist2 = dotProduct(q, q);
      }
      if (dist2 > worst) {
        worst = dist2;
        worstIdx = i;
      }
    }
    if (worst > eps2) {
      numkeep++;
      keep[worstIdx] = 1;
      stack.push_back(std::make_pair(a, worstIdx));
      stack.push_back(std::make_pair(worstIdx, b));
    }
  }
  std::vector<Vector2> out;
  out.reserve(numkeep + 1);
  for (int i = 0; i < n; i++)
    if (keep[i])
      out.push_back(pts[i]);
  return out;
}

struct Quality {
  int capSegments; // per half circle
  float joinStep;  // max angle per join-fan triangle
  float epsilon;   // path simplification tolerance, playfield units
};

// This function is not mine, im not gonna claim it. 
// (it doesnt even work correctly lol)
Quality qualityFor(float radius) {
  float rPx = fabsf(ScaleCordX(radius) - ScaleCordX(0.0f));
  if (rPx < 1.0f)
    rPx = 1.0f;
  float dTheta =
      2.0f * acosf(clipFloat(1.0f - MESHSLIDER_SAG_PX / rPx, -1.0f, 1.0f));
  int cap = (int)(ceilf(PI / std::max(dTheta, 0.01f)));
  #ifdef THREEDS_BUILD
  cap = std::max(6, std::min(24, cap));
  #else
  cap = std::max(12, std::min(24, cap));
  #endif
  return {cap, PI / static_cast<float>(cap), MESHSLIDER_SAG_PX * radius / rPx};
}

// ok so we only refresh the point cache when the source changes, be it snake 
// in or out. of course, the reserves are for like, heap health? i guess?
// should only run once per slider right now, i hope
void refreshCache(MeshSliderCache &c, const std::vector<Vector2> &src,
                  float radius) {
  if (!c.points.empty() && c.srcData == src.data() &&
      c.srcCount == src.size() && AreSame(c.radius, radius) &&
      c.meshW == allocatedWidth && c.meshH == allocatedHeight)
    return;
  float eps = qualityFor(radius).epsilon;
  float threshold = std::max(1.0f, Global.adaptiveRdpThreshold);
  if (src.size() > threshold) {
    float factor = sqrtf(src.size() / threshold);
    eps *= clipFloat(factor, 1.0f, 8.0f);
  }
  c.points = simplifyPath(src, eps); // Long sliders are just pain bruh
  c.meshValid = false;
  dedupePoints(c.points, 0.01f);
  c.arcLength.assign(c.points.size(), 0.0f);
  for (size_t i = 1; i < c.points.size(); i++) {
    Vector2 d = subVectors(c.points[i], c.points[i - 1]);
    c.arcLength[i] = c.arcLength[i - 1] + sqrtf(dotProduct(d, d));
  }
  c.srcData = src.data();
  c.srcCount = src.size();
  c.radius = radius;

  size_t n = c.points.size();
  size_t maxVerts =
      (n > 1 ? (n - 1) * 15 : 0) + qualityFor(radius).capSegments * 6;
  c.mesh.clear();
  c.mesh.reserve(maxVerts);
  c.dirs.clear();
  c.dirs.resize(n > 1 ? n - 1 : 0);
  for (size_t i = 0; i + 1 < n; i++) {
    Vector2 d = subVectors(c.points[i + 1], c.points[i]);
    float len = sqrtf(dotProduct(d, d));
    c.dirs[i] = len > 1e-6f ? scaleVector(d, 1.0f / len) : Vector2{1.0f, 0.0f};
  }
  c.segStart.assign(n > 1 ? n - 1 : 0, 0);
  c.joinStart.assign(n, 0);
  c.joinCount.assign(n, 0);
  c.cap0Start = c.cap1Start = 0;
  c.builtVerts = 0;
  c.builtSeg = 0;
  c.builtJoin = 0;
  c.cap0Done = c.cap1Done = false;
  c.meshValid = true;
  c.meshW = allocatedWidth;
  c.meshH = allocatedHeight;
}

// Index of the segment whose arc-length span contains d, and the point on the
// centerline at arc length d (linearly interpolated within that segment).
// Both cuts always land on a segment, so interior vertices never need
// regenerating - only the ridge/cap at the moving cut.

// This saves so much memory and cpu that its not even funny
int segmentAt(const MeshSliderCache &c, float d) {
  int n = c.points.size();
  if (n < 2)
    return 0;
  int i = 
      std::upper_bound(c.arcLength.begin(), c.arcLength.end(), d) -
      c.arcLength.begin();
  if (i == 0)
    return 0;
  if (i >= n)
    return n - 2;
  return i - 1;
}

Vector2 pointAt(const MeshSliderCache &c, float d) {
  int n = c.points.size();
  if (n == 0)
    return {0.0f, 0.0f};
  if (n == 1)
    return c.points[0];
  int i = 
      std::upper_bound(c.arcLength.begin(), c.arcLength.end(), d) -
      c.arcLength.begin();
  if (i == 0)
    return c.points[0];
  if (i >= n)
    return c.points[n - 1];
  float seg = c.arcLength[i] - c.arcLength[i - 1];
  float t = seg > 0.0f ? (d - c.arcLength[i - 1]) / seg : 0.0f;
  Vector2 a = c.points[i - 1], b = c.points[i];
  return {a.x + (b.x - a.x) * t, a.y + (b.y - a.y) * t};
}

// target coords are inverted on pc/opengl
Vector2 toTarget(Vector2 point) {
  float widthRatio = 1.0f;
  float heightRatio = 1.0f;
  if (allocatedWidth > 0 && allocatedHeight > 0) {
    widthRatio = (float)(allocatedWidth) /
                 (float)(GetScreenWidth());
    heightRatio = (float)(allocatedHeight) /
                  (float)(GetScreenHeight());
  }
  float x = ScaleCordX(point.x) * widthRatio;
  float y = ScaleCordY(point.y) * heightRatio;
#ifdef THREEDS_BUILD
  return {x, y};
#else
  return {x, allocatedHeight - y};
#endif
}

void emitVertex(std::vector<TexturedVertex> &out, Vector2 p, float u) {
  // depth is linear in u 
  // a cone around every path point
  // this solves intersections in a cool way
  float depth = DEPTH_CENTRE + (DEPTH_EDGE - DEPTH_CENTRE) * u;
  out.push_back({toTarget(p), {lutCoord(u), 0.5f}, depth});
}

void emitTriangle(std::vector<TexturedVertex> &out, Vector2 a, float ua,
                  Vector2 b, float ub, Vector2 c, float uc) {
  emitVertex(out, a, ua);
  emitVertex(out, b, ub);
  emitVertex(out, c, uc);
}

// Geometry emitters. Each writes 3*steps TexturedVertex.
// One ridge for segment a->b. 12 vertices (4 triangles).
void emitRidge(std::vector<TexturedVertex> &out, Vector2 a, Vector2 b,
               Vector2 dir, float radius) {
  Vector2 nrm = {-dir.y, dir.x};
  Vector2 off = scaleVector(nrm, radius);
  Vector2 al = addVectors(a, off), ar = subVectors(a, off);
  Vector2 bl = addVectors(b, off), br = subVectors(b, off);
  emitTriangle(out, al, 1.0f, bl, 1.0f, b, 0.0f);
  emitTriangle(out, al, 1.0f, b, 0.0f, a, 0.0f);
  emitTriangle(out, a, 0.0f, b, 0.0f, br, 1.0f);
  emitTriangle(out, a, 0.0f, br, 1.0f, ar, 1.0f);
}

// Round outer join at point k
int emitJoin(std::vector<TexturedVertex> &out, const MeshSliderCache &c, int k,
             float radius, const Quality &q) {
  Vector2 d0 = c.dirs[k - 1], d1 = c.dirs[k];
  float cross = d0.x * d1.y - d0.y * d1.x;
  float s = cross > 0.0f ? -1.0f : 1.0f;
  Vector2 m0 = {s * -d0.y, s * d0.x};
  Vector2 m1 = {s * -d1.y, s * d1.x};
  float ang = atan2f(m0.x * m1.y - m0.y * m1.x, dotProduct(m0, m1));
  if (fabsf(ang) < 1e-4f)
    return 0;
  if (fabsf(ang) > PI - 0.01f) {
    Vector2 mid = {-m0.y, m0.x};
    ang = dotProduct(mid, d0) >= 0.0f ? PI : -PI;
  }
  int steps = std::max(1, (int)(ceilf(fabsf(ang) / q.joinStep)));
  Vector2 centre = c.points[k];
  Vector2 prev = addVectors(centre, scaleVector(m0, radius));
  for (int j = 1; j <= steps; j++) {
    float th = ang * j / steps;
    float cc = cosf(th), sn = sinf(th);
    Vector2 m = {m0.x * cc - m0.y * sn, m0.x * sn + m0.y * cc};
    Vector2 cur = addVectors(centre, scaleVector(m, radius));
    emitTriangle(out, centre, 0.0f, prev, 1.0f, cur, 1.0f);
    prev = cur;
  }
  return steps * 3;
}

// Round cap (half circle facing outward).
void emitCap(std::vector<TexturedVertex> &out, Vector2 centre, Vector2 tangent,
             float radius, const Quality &q) {
  float base = atan2f(tangent.y, tangent.x);
  for (int i = 0; i < q.capSegments; i++) {
    float a0 = base - PI / 2.0f + i * PI / q.capSegments;
    float a1 = base - PI / 2.0f + (i + 1) * PI / q.capSegments;
    Vector2 p0 =
        addVectors(centre, Vector2{cosf(a0) * radius, sinf(a0) * radius});
    Vector2 p1 =
        addVectors(centre, Vector2{cosf(a1) * radius, sinf(a1) * radius});
    emitTriangle(out, centre, 0.0f, p0, 1.0f, p1, 1.0f);
  }
}

// Full disc for a single collapsed point.
void emitDisc(std::vector<TexturedVertex> &out, Vector2 centre, float radius,
              const Quality &q) {
  int steps = q.capSegments * 2;
  for (int i = 0; i < steps; i++) {
    float a0 = 2.0f * PI * i / steps, a1 = 2.0f * PI * (i + 1) / steps;
    emitTriangle(out, centre, 0.0f,
                 {centre.x + cosf(a0) * radius, centre.y + sinf(a0) * radius},
                 1.0f,
                 {centre.x + cosf(a1) * radius, centre.y + sinf(a1) * radius},
                 1.0f);
  }
}

// Ensure the cached mesh contains all geometry up to arc length dmax. Pieces
// are appended once, in path order: [cap0][ridge0][join1][ridge1]...[cap1].
// Repeated calls with growing dmax only emit newly exposed pieces.
void ensureMeshUpTo(MeshSliderCache &c, float radius, const Quality &q,
                    float dmax) {
  int n = (int)(c.points.size());
  if (n < 2)
    return;
  float total = c.arcLength.back();
  dmax = clipFloat(dmax, 0.0f, total);

  if (!c.cap0Done) {
    c.cap0Start = (int)(c.mesh.size());
    emitCap(c.mesh, c.points[0], Vector2{-c.dirs[0].x, -c.dirs[0].y}, radius, q);
    c.cap0Done = true;
  }

  for (int s = c.builtSeg; s < n - 1; s++) {
    if (c.arcLength[s] > dmax)
      break;
    if (s >= 1 && c.joinCount[s] == 0 && c.arcLength[s] < dmax) {
      c.joinStart[s] = (int)(c.mesh.size());
      c.joinCount[s] = emitJoin(c.mesh, c, s, radius, q);
    }
    if (c.arcLength[s + 1] > dmax) {
      c.segStart[s] = (int)(c.mesh.size());
      break;
    }
    c.segStart[s] = (int)(c.mesh.size());
    emitRidge(c.mesh, c.points[s], c.points[s + 1], c.dirs[s], radius);
    c.builtSeg = s + 1;
  }

  if (dmax >= total && !c.cap1Done) {
    c.cap1Start = (int)(c.mesh.size());
    emitCap(c.mesh, c.points[n - 1], c.dirs[n - 2], radius, q);
    c.cap1Done = true;
  }
  c.builtVerts = (int)(c.mesh.size());
}

void releaseTarget() {
  if (!targetReady)
    return;
  UnloadRenderTexture(&sharedTarget);
  targetReady = false;
}


void MeshSliderInit() {
  if (targetReady)
    return;
  int width = GetScreenWidth();
  int height = GetScreenHeight();
  if (width < 2)
    width = 2;
  if (height < 2)
    height = 2;
  sharedTarget = LoadRenderTexture(width, height);
  targetReady = sharedTarget.id != 0;
  std::cout << "\e[1;38;5;236m[INFO] \e[38;5;40m" << "Slider Texture allocated"
            << std::endl;
  allocatedWidth = width;
  allocatedHeight = height;
}

void MeshSliderFreeResources() {
  releaseTarget();
  for (size_t i = 0; i < lutCount; i++)
    UnloadRenderTexture(&luts[i].target);
  lutCount = 0;
  lutEvictCursor = 0;
  allocatedWidth = 0;
  allocatedHeight = 0;
#ifdef THREEDS_BUILD
  MeshVboFree();
#endif
}

void MeshSliderRender(const MeshSliderDrawData &data) {
  if (targetReady &&
      (allocatedWidth != GetScreenWidth() ||
       allocatedHeight != GetScreenHeight())) // check for resized window
    releaseTarget();
  MeshSliderInit();
  if (!targetReady || data.points == nullptr || data.points->empty())
    return;
  if (data.alpha <= 0.0f || data.radius <= 0.0f)
    return;

  Color accent = {data.bodyColour.r, data.bodyColour.g, data.bodyColour.b, 255};
  RenderTexture2D *lut = getLut(accent);
  if (lut == nullptr)
    return;
  Texture2D lutTex = lut->texture;

  MeshSliderCache localCache;
  MeshSliderCache &cache = data.cache ? *data.cache : localCache;
  refreshCache(cache, *data.points, data.radius * MESH_SLIDER_SHADOW_SCALE);
  int n = (int)(cache.points.size());
  if (n < 1)
    return;

  Quality q = qualityFor(data.radius * MESH_SLIDER_SHADOW_SCALE);
  float radius = data.radius * MESH_SLIDER_SHADOW_SCALE;
  float total = cache.arcLength.back();

  // Build the full mesh once. For snake-in only the exposed prefix is
  // emitted, so the work is spread across frames instead of one big rebuild.
  ensureMeshUpTo(cache, radius, q, total);

  float startD = clipFloat(data.startProgress, 0.0f, 1.0f) * total;
  float endD = clipFloat(data.endProgress, 0.0f, 1.0f) * total;
  if (endD <= startD)
    endD = startD + 0.01f; // keep a dot alive

  // A visible sub-range is one contiguous slice [lo, hi); the cut ridges/caps are regenerated in scratch.
  int lo = 0;
  int hi = (int)(cache.mesh.size());
  std::vector<TexturedVertex> cutScratch;
  Vector2 cutPoint = pointAt(cache, endD);
  Vector2 startPoint = pointAt(cache, startD);

  bool collapsed = (endD - startD) <= 0.01f;
  if (collapsed) {
    lo = 0;
    hi = 0;
    emitDisc(cutScratch, startPoint, radius, q);
  } else if (startD <= 0.0f && endD >= total) {
    lo = 0;
    hi = (int)(cache.mesh.size());
  } else {
    int s0 = segmentAt(cache, startD);
    int s1 = segmentAt(cache, endD);
    if (endD < total)
      hi = cache.segStart[s1];
    else
      hi = (int)(cache.mesh.size());

    lo = hi; // empty interior by default
    int firstInterior = s0 + 1;
    if (startD > 0.0f && firstInterior <= n - 2) {
      lo = cache.joinCount[firstInterior] > 0
               ? cache.joinStart[firstInterior]
               : cache.segStart[firstInterior];
    } else if (startD <= 0.0f) {
      lo = 0;
    }
    if (lo > hi)
      lo = hi;
    if (endD >= total && cache.cap1Done && lo >= cache.cap1Start)
      lo = cache.cap1Start;

    // Regenerate the cut ridge/caps. When both cuts are in the SAME segment,
    // emit a single ridge between them.
    if (s0 == s1) {
      emitRidge(cutScratch, startPoint, cutPoint, cache.dirs[s0], radius);
      if (startD > 0.0f)
        emitCap(cutScratch, startPoint,
                Vector2{-cache.dirs[s0].x, -cache.dirs[s0].y}, radius, q);
      if (endD < total)
        emitCap(cutScratch, cutPoint, cache.dirs[s1], radius, q);
    } else {
      if (startD > 0.0f) {
        Vector2 b = (s0 + 1 < n) ? cache.points[s0 + 1] : startPoint;
        emitRidge(cutScratch, startPoint, b, cache.dirs[s0], radius);
        emitCap(cutScratch, startPoint,
                Vector2{-cache.dirs[s0].x, -cache.dirs[s0].y}, radius, q);
      }
      if (endD < total) {
        emitRidge(cutScratch, cache.points[s1], cutPoint, cache.dirs[s1], radius);
        emitCap(cutScratch, cutPoint, cache.dirs[s1], radius, q);
      }
    }
  }
  int screenWidth = GetScreenWidth();
  int screenHeight = GetScreenHeight();
  float minX = cache.points[0].x, maxX = minX;
  float minY = cache.points[0].y, maxY = minY;
  for (int i = 1; i < n; i++) {
    minX = std::min(minX, cache.points[i].x);
    maxX = std::max(maxX, cache.points[i].x);
    minY = std::min(minY, cache.points[i].y);
    maxY = std::max(maxY, cache.points[i].y);
  }
  // todo, this outer box check could be way better?

  Vector2 screenTL = {ScaleCordX(minX - 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE),
                      ScaleCordY(minY - 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE)};
  Vector2 screenBR = {ScaleCordX(maxX + 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE),
                      ScaleCordY(maxY + 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE)};
  // small margins for a bit more space i guess?

  int screenX = clipFloat(std::min(screenTL.x, screenBR.x), 0.0f, screenWidth);
  int screenY = clipFloat(std::min(screenTL.y, screenBR.y), 0.0f, screenHeight);
  int regionW =
      clipFloat(std::max(screenTL.x, screenBR.x), 0.0f, screenWidth) - screenX;
  int regionH =
      clipFloat(std::max(screenTL.y, screenBR.y), 0.0f, screenHeight) - screenY;
  if (regionW < 1 || regionH < 1)
    return;

  Vector2 targetTL =
      toTarget({minX - 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE, minY - 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE});
  Vector2 targetBR =
      toTarget({maxX + 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE, maxY + 1.2f * data.radius * MESH_SLIDER_SHADOW_SCALE});
  int targetX =
      clipFloat(std::min(targetTL.x, targetBR.x), 0.0f, allocatedWidth);
  int targetY =
      clipFloat(std::min(targetTL.y, targetBR.y), 0.0f, allocatedHeight);
  int targetW =
      clipFloat(std::max(targetTL.x, targetBR.x), 0.0f, allocatedWidth) -
      targetX;
  int targetH =
      clipFloat(std::max(targetTL.y, targetBR.y), 0.0f, allocatedHeight) -
      targetY;
  if (targetW < 1 || targetH < 1)
    return;

  BeginTextureMode(&sharedTarget);

#ifdef THREEDS_BUILD
  C2D_Flush();
  C3D_DepthTest(true, GPU_ALWAYS, GPU_WRITE_ALL);
  rlSetBlendFactorsSeparate(RL_ONE, RL_ZERO, RL_ONE, RL_ZERO, REPLACE_EQUATION,
                            REPLACE_EQUATION);
  rlSetBlendMode(RL_BLEND_CUSTOM_SEPARATE);
  C2D_DrawRectSolid(targetX, targetY,
                    0.0f, targetW,
                    targetH, 0);
  C2D_Flush();
  C3D_DepthTest(true, GPU_GREATER, GPU_WRITE_ALL);
  C3D_CullFace(GPU_CULL_NONE);
#else
  rlDrawRenderBatchActive();
  rlEnableDepthTest();
  rlEnableDepthMask();
  rlDepthFuncAlways();
  rlSetBlendFactorsSeparate(RL_ONE, RL_ZERO, RL_ONE, RL_ZERO, REPLACE_EQUATION,
                            REPLACE_EQUATION);
  rlSetBlendMode(RL_BLEND_CUSTOM_SEPARATE);
  rlSetTexture(0);

  // bilinear filtering yum~!
  float clearX0 = std::max(0.0f, targetX - 2.0f);
  float clearY0 = std::max(0.0f, targetY - 2.0f);
  float clearX1 = std::min(allocatedWidth, targetX + targetW + 2);
  float clearY1 = std::min(allocatedHeight, targetY + targetH + 2);

  rlBegin(RL_QUADS);
  rlColor4ub(0, 0, 0, 0);
  rlVertex3f(clearX0, clearY0, DEPTH_MULT * 0.95f);
  rlVertex3f(clearX0, clearY1, DEPTH_MULT * 0.95f);
  rlVertex3f(clearX1, clearY1, DEPTH_MULT * 0.95f);
  rlVertex3f(clearX1, clearY0, DEPTH_MULT * 0.95f);
  rlEnd();
  rlDrawRenderBatchActive();
  rlCustomDepthFunc(false);
  rlDisableBackfaceCulling();
#endif

  rlSetBlendFactorsSeparate(RL_ONE, RL_ZERO, RL_ONE, RL_ZERO, REPLACE_EQUATION,
                            REPLACE_EQUATION);
  rlSetBlendMode(RL_BLEND_CUSTOM_SEPARATE);
  Color tint = Fade(WHITE, data.alpha);
  if (lo < hi)
    DrawTexturedTrianglesDepth(&lutTex, cache.mesh.data() + lo, hi - lo, tint);
  if (!cutScratch.empty())
    DrawTexturedTrianglesDepth(&lutTex, cutScratch.data(),
                               (int)(cutScratch.size()), tint);

#ifdef THREEDS_BUILD
  C3D_DepthTest(false, GPU_ALWAYS, GPU_WRITE_COLOR); // depth writing we dont need, so not using disabledepthtest
#else
  rlDrawRenderBatchActive();
  rlDisableDepthTest();
#endif
  EndTextureMode();
  EndBlendMode();
  DrawTexturePro(
      &sharedTarget.texture,
      Rectangle{static_cast<float>(screenX), static_cast<float>(screenY),
                static_cast<float>(regionW), static_cast<float>(regionH)},
      Rectangle{static_cast<float>(screenX), static_cast<float>(screenY),
                static_cast<float>(regionW), static_cast<float>(regionH)},
      Vector2{0.0f, 0.0f}, 0.0f, WHITE);
}