const int LUT_SIZE = 128;
const int LUT_ROWS = 8;
const size_t MAX_LUTS = 24; // distinct combo colours kept alive
const float BORDER_PORTION = 0.192f;
#ifdef THREEDS_BUILD
const float AA_PORTION = 0.06f;
#else
const float AA_PORTION = 0.02f;
#endif
const float OPACITY_AT_EDGE = 0.6f;
const float OPACITY_AT_CENTRE = 0.6f;
const float SHADOW_ALPHA = 0.35f;

// Geometry quality is derived from the ON-SCREEN radius so we never spend
// triangles that are smaller than a fraction of a pixel (3DS: ~10 segments per
// half cap, 1080p desktop: ~20). Max allowed deviation of any polygonal curve
// from the true circle / centre line, in screen pixels:
#ifndef MESHSLIDER_SAG_PX
#ifdef THREEDS_BUILD
#define MESHSLIDER_SAG_PX 1.0f
#else
#define MESHSLIDER_SAG_PX 0.7f
#endif
#endif

#ifndef MESHSLIDER_SWAP_DEPTH
#define MESHSLIDER_SWAP_DEPTH 1
#endif

#ifdef THREEDS_BUILD
const GPU_BLENDEQUATION REPLACE_EQUATION = GPU_BLEND_ADD;
const float DEPTH_HI = 0.1f;
const float DEPTH_LO = 0.02f;
#else
const int REPLACE_EQUATION = RL_FUNC_ADD;
const float DEPTH_HI = DEPTH_MULT * 0.9f;
const float DEPTH_LO = DEPTH_MULT * 0.3f;
#endif
const float DEPTH_CENTRE = MESHSLIDER_SWAP_DEPTH ? DEPTH_LO : DEPTH_HI;
const float DEPTH_EDGE = MESHSLIDER_SWAP_DEPTH ? DEPTH_HI : DEPTH_LO;

